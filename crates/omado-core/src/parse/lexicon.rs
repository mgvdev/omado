//! Mots de la saisie rapide, par langue (hors chinois et japonais, voir `cjk`).
//!
//! Chaque langue liste ses formes (déclinaisons, abréviations, locutions de
//! plusieurs mots) pour des sens communs, que la grammaire de `super` combine.
//! Les formes sont comparées sans casse ni accents (`fold`) : « manana »
//! vaut « mañana ».
//!
//! Actives : l'anglais, le français et le russe (alphabet sans ambiguïté avec
//! les autres), plus la langue de l'interface. Mélanger toutes les langues à
//! alphabet latin créerait des faux positifs : l'espagnol « 2 o 3 manzanas »
//! deviendrait « à 3 h » avec la règle polonaise « o 9 ».

use std::collections::HashMap;
use std::sync::{Mutex, OnceLock};

use chrono::Weekday::{self, *};

use super::fold;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Unit {
    Day,
    Week,
    Month,
    Year,
    Hour,
    Minute,
}

/// Sens d'une forme.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum W {
    Today,
    Tomorrow,
    AfterTomorrow,
    /// Ce soir : aujourd'hui, 19 h par défaut.
    Tonight,
    ThisWeekend,
    NextWeek,
    NextMonth,
    /// Avant un jour : « next », « nächsten », « próximo ».
    Next,
    /// Après un jour : « prochain », « prossimo », « que viene ».
    NextAfter,
    /// Avant un délai : « dans », « in », « tra », « через », « za ».
    In,
    Unit(Unit),
    Number(u32),
    Weekday(Weekday),
    /// Jour abrégé ambigu (portugais « segunda » : lundi ou « deuxième ») :
    /// reconnu seulement après un mot qui annonce un jour.
    WeakWeekday(Weekday),
    /// Habitude : « montags », « los lunes », « по понедельникам », « mondays ».
    Habitual(Weekday),
    Month(u32),
    /// Avant une date ou une heure : « le », « on », « am », « el », « в ».
    Connector,
    /// Avant une heure donnée sans unité : « at 9 », « um 9 », « a las 9 ».
    At,
    /// Après l'heure : « Uhr », « часов », « horas ».
    HourWord,
    Noon,
    Midnight,
    Am,
    Pm,
    /// Après l'heure : « y media », « e mezza », « e meia ».
    Half,
    /// « every », « chaque », « tous les », « jeden », « cada », « каждый », « co ».
    Every,
    /// « every other week » : un sur deux.
    Other,
    Daily,
    Weekly,
    Monthly,
    Yearly,
    WeekdaysOnly,
    /// Jour ouvré comme unité : « every weekday », « jeden Werktag ».
    WeekdayUnit,
    /// Week-end comme unité : « every weekend », « jedes Wochenende ».
    Weekend,
    /// Habitude du week-end : « по выходным », « w weekendy ».
    Weekends,
    And,
    /// Entre le jour et le mois : « 15 de octubre ».
    Of,
    /// Avant un numéro de jour : « le 15 », « the 15th », « el día 15 ».
    DayOfMonth,
    /// Idem, mais le numéro doit porter son suffixe : « the 15th » (« the 3 books » n'est pas une date).
    DayOfMonthOrdinal,
    /// Après un numéro de jour : « 15 числа ».
    DayOfMonthAfter,
    Morning,
    Afternoon,
    Evening,
}

