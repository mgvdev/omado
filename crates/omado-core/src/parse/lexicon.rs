/// Langues à alphabet latin qui ne s'activent qu'en langue d'interface.
const BY_INTERFACE: &[(&str, Table)] = &[("de", DE), ("es", ES), ("it", IT), ("pt_BR", PT_BR), ("pl", PL)];

/// Formes actives, indexées par leur premier mot (sans casse ni accents).
pub struct Lexicon {
    by_first: HashMap<String, Vec<(Vec<String>, W)>>,
}

impl Lexicon {
    fn build(tables: &[Table]) -> Lexicon {
        let mut by_first: HashMap<String, Vec<(Vec<String>, W)>> = HashMap::new();
        for (meaning, phrase) in tables.iter().flat_map(|t| t.iter()) {
            let words: Vec<String> = fold(phrase).split_whitespace().map(String::from).collect();
            by_first.entry(words[0].clone()).or_default().push((words, *meaning));
        }
        // Les locutions les plus longues d'abord : « la semaine prochaine » avant « la ».
        for entries in by_first.values_mut() {
            entries.sort_by_key(|(words, _)| std::cmp::Reverse(words.len()));
        }
        Lexicon { by_first }
    }

    /// Lexique pour la langue d'interface `code`.
    pub fn for_language(code: &str) -> &'static Lexicon {
        static CACHE: OnceLock<Mutex<HashMap<String, &'static Lexicon>>> = OnceLock::new();
        let mut cache = CACHE.get_or_init(Default::default).lock().unwrap_or_else(|e| e.into_inner());
        cache.entry(code.to_string()).or_insert_with(|| {
            let mut tables = vec![EN, FR, RU];
            tables.extend(BY_INTERFACE.iter().filter(|(c, _)| *c == code).map(|(_, t)| *t));
            Box::leak(Box::new(Lexicon::build(&tables)))
        })
    }

    /// Sens reconnus à partir de `words[0]`, avec leur longueur en mots, les plus longs d'abord.
    pub fn at<'a>(&'a self, words: &'a [&'a str]) -> impl Iterator<Item = (W, usize)> + 'a {
        let entries = words.first().and_then(|first| self.by_first.get(*first));
        entries.into_iter().flatten().filter_map(move |(phrase, meaning)| {
            (words.len() >= phrase.len() && phrase.iter().zip(words).all(|(p, w)| p == w))
                .then_some((*meaning, phrase.len()))
        })
    }
}
